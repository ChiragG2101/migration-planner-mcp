// Generate eval/results.md (M7 task 6, D17, INV-43). A pure function of HEAD's
// tree: no generation time, cost and wall time come from the recorded runs, the
// engine is recorded by its package version (never a git SHA), and it always
// reports each pack's all-case beat result and renders REMOVED.json. The same
// tree always yields the same bytes. Base-dependent verdicts (regression,
// widening) are NOT here; they go in the CI job output (packGate notes).
import { ENGINE_VERSION } from '../src/core/index.js';
import { bandFigure, bestRun, ratio, worstRun, type CaseRunRecall, type Tally } from './metrics.js';
import type { RemovedEntry } from './schema.js';

/** A pack's scored runs, ready to render. */
export interface PackResult {
  pack: string;
  present: boolean; // true when packs/<pack>/ exists at HEAD
  engine: Map<string, CaseRunRecall[]>;
  baseline: Map<string, CaseRunRecall[]>;
}

export interface ResultsInput {
  /** Hashes/versions recorded in the header (pure function of HEAD). */
  prompt_version: string;
  gates_hash: string;
  packs: PackResult[];
  /** Cases whose pack is not under packs/ at HEAD (listed as pending). */
  pending_cases: { id: string; pack: string }[];
  removed: RemovedEntry[];
  /** Empty cells of the coverage matrix (known gaps). */
  coverage_gaps: string[];
  /** PR-missed annotations per case (INV-30): shown in their own section, never in the headline. */
  annotations?: { case_id: string; finding: string; reason: string; reviewer: string; date: string }[];
}

const pct = (t: Tally): string => `${t.found}/${t.total} (${(ratio(t) * 100).toFixed(1)}%)`;

export function renderResults(input: ResultsInput): string {
  const lines: string[] = [
    '# Eval results',
    '',
    'Generated by `npm run eval` (`eval/runner.ts`); do not edit by hand (`docs/design.md` D17). This file is a pure function of HEAD\'s tree: it carries no generation time, takes cost and wall time from the recorded runs, and records the engine by its package version. Base-branch verdicts (regression, widening) live in the CI job output, not here.',
    '',
    `- Engine version: \`${ENGINE_VERSION}\``,
    `- Prompt version: \`${input.prompt_version}\``,
    `- Gates hash: \`${input.gates_hash}\``,
    '',
  ];

  for (const pack of [...input.packs].sort((a, b) => a.pack.localeCompare(b.pack))) {
    lines.push(`## Pack \`${pack.pack}\``, '');
    const caseIds = [...new Set([...pack.engine.keys(), ...pack.baseline.keys()])].sort();
    if (caseIds.length === 0) {
      lines.push('No recorded golden runs yet.', '');
      continue;
    }
    const engineFig = bandFigure(pack.engine, worstRun);
    const baselineFig = bandFigure(pack.baseline, bestRun);
    const engineBest = bandFigure(pack.engine, bestRun);
    const baselineWorst = bandFigure(pack.baseline, worstRun);

    lines.push('### Noise band (pooled usage recall)', '');
    lines.push('| Side | Worst-run pooled | Best-run pooled |', '| --- | --- | --- |');
    lines.push(`| Engine | ${pct(engineFig.pooled)} | ${pct(engineBest.pooled)} |`);
    lines.push(`| Baseline | ${pct(baselineWorst.pooled)} | ${pct(baselineFig.pooled)} |`, '');

    const beats = ratio(engineFig.pooled) > ratio(baselineFig.pooled);
    lines.push(
      `All-case beat result: engine worst-case pooled recall ${pct(engineFig.pooled)} vs baseline best-case pooled recall ${pct(baselineFig.pooled)} \u2014 **the engine ${beats ? 'beats' : 'does NOT beat'} the baseline**.`,
      '',
    );

    lines.push('### Per case (covered / true changed usages)', '');
    lines.push('| Case | Engine worst | Engine best | Baseline worst | Baseline best |', '| --- | --- | --- | --- | --- |');
    for (const id of caseIds) {
      const e = pack.engine.get(id) ?? [];
      const b = pack.baseline.get(id) ?? [];
      const cell = (runs: CaseRunRecall[], pick: (r: readonly CaseRunRecall[]) => CaseRunRecall): string =>
        runs.length ? `${pick(runs).covered}/${pick(runs).total}` : '-';
      lines.push(`| \`${id}\` | ${cell(e, worstRun)} | ${cell(e, bestRun)} | ${cell(b, worstRun)} | ${cell(b, bestRun)} |`);
    }
    lines.push('');
  }

  if (input.pending_cases.length) {
    lines.push('## Pending cases', '', 'Cases whose pack is not under `packs/` at HEAD; listed, never scored or failed.', '');
    for (const c of [...input.pending_cases].sort((a, b) => a.id.localeCompare(b.id))) lines.push(`- \`${c.id}\` (pack \`${c.pack}\`)`);
    lines.push('');
  }

  lines.push('## Coverage gaps (known)', '');
  if (input.coverage_gaps.length) for (const g of [...input.coverage_gaps].sort()) lines.push(`- ${g}`);
  else lines.push('None.');
  lines.push('');

  const annotations = input.annotations ?? [];
  lines.push('## PR missed (annotations)', '');
  lines.push('Reviewer-recorded cases where the real PR itself missed a required change. Headline metrics above stay computed from raw truth (`docs/design.md` D7); these only add an adjusted view.', '');
  if (annotations.length) {
    lines.push('| Case | Finding | Reason | Reviewer | Date |', '| --- | --- | --- | --- | --- |');
    for (const a of [...annotations].sort((x, y) => (x.case_id + x.finding).localeCompare(y.case_id + y.finding))) {
      lines.push(`| \`${a.case_id}\` | ${a.finding} | ${a.reason} | ${a.reviewer} | ${a.date} |`);
    }
  } else lines.push('None.');
  lines.push('');

  lines.push('## Removed cases', '');
  if (input.removed.length) {
    lines.push('| Case | Reason | PR |', '| --- | --- | --- |');
    for (const r of [...input.removed].sort((a, b) => a.id.localeCompare(b.id))) lines.push(`| \`${r.id}\` | ${r.reason} | ${r.pr} |`);
  } else lines.push('None.');
  lines.push('');

  return `${lines.join('\n')}\n`;
}
