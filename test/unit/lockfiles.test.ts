// Lockfile parsing: npm (v1, v3), pnpm (v5, v6+, v9), yarn (v1, berry), uv, poetry, requirements.
import { describe, expect, it } from 'vitest';
import { parsePackageLock, parsePnpmLock, parseYarnLock, parseJsonc } from '../../src/analysis/manifests/node.js';
import {
  normalizePyName,
  parsePackageListLock,
  parsePyproject,
  parseRequirement,
  parseRequirements,
  pinnedVersion,
} from '../../src/analysis/manifests/python.js';

describe('npm package-lock.json', () => {
  it('v3: the importer copy wins over the hoisted one', () => {
    const lookup = parsePackageLock(
      JSON.stringify({
        lockfileVersion: 3,
        packages: {
          'node_modules/next': { version: '14.2.35' },
          'apps/web/node_modules/next': { version: '13.5.6' },
          'node_modules/linked': { version: '1.0.0', link: true },
        },
      }),
    );
    expect(lookup('next', '', null)).toEqual(['14.2.35']);
    expect(lookup('next', 'apps/web', null)).toEqual(['13.5.6']);
    expect(lookup('next', 'apps/docs', null)).toEqual(['14.2.35']);
    expect(lookup('react', '', null)).toEqual([]);
    expect(lookup('linked', '', null)).toEqual([]);
  });

  it('v1: the dependencies table', () => {
    const lookup = parsePackageLock(JSON.stringify({ lockfileVersion: 1, dependencies: { next: { version: '12.3.4' } } }));
    expect(lookup('next', '', null)).toEqual(['12.3.4']);
  });
});

describe('pnpm-lock.yaml', () => {
  it('v9 importers with peer suffixes stripped', () => {
    const lookup = parsePnpmLock(`lockfileVersion: '9.0'
importers:
  .:
    dependencies:
      next:
        specifier: ^14.2.0
        version: 14.2.35(react-dom@18.3.1(react@18.3.1))(react@18.3.1)
  apps/web:
    devDependencies:
      next:
        specifier: ^15.0.0
        version: 15.1.0(react@19.0.0)
      shared:
        specifier: workspace:*
        version: link:../../packages/shared
`);
    expect(lookup('next', '', null)).toEqual(['14.2.35']);
    expect(lookup('next', 'apps/web', null)).toEqual(['15.1.0']);
    expect(lookup('shared', 'apps/web', null)).toEqual([]);
    expect(lookup('next', 'apps/missing', null)).toEqual([]);
  });

  it('v5 single project: top-level dependencies with underscore peer suffix', () => {
    const lookup = parsePnpmLock(`lockfileVersion: 5.4
specifiers:
  next: ^13.0.0
dependencies:
  next: 13.5.6_react@18.2.0
`);
    expect(lookup('next', '', null)).toEqual(['13.5.6']);
  });
});

describe('yarn.lock', () => {
  it('v1: by exact spec, else every version of the name', () => {
    const lookup = parseYarnLock(`# THIS IS AN AUTOGENERATED FILE.
# yarn lockfile v1


"@next/env@14.2.35":
  version "14.2.35"

next@^14.2.0, next@^14.2.3:
  version "14.2.35"
  resolved "https://registry.yarnpkg.com/next/-/next-14.2.35.tgz"

next@^13.0.0:
  version "13.5.6"
`);
    expect(lookup('next', '', '^14.2.3')).toEqual(['14.2.35']);
    expect(lookup('next', '', '^13.0.0')).toEqual(['13.5.6']);
    expect(lookup('next', '', null)).toEqual(['13.5.6', '14.2.35']);
    expect(lookup('@next/env', '', '14.2.35')).toEqual(['14.2.35']);
  });

  it('berry: npm: protocol specs and unquoted version', () => {
    const lookup = parseYarnLock(`__metadata:
  version: 8

"next@npm:^15.0.0":
  version: 15.1.0
  resolution: "next@npm:15.1.0"
`);
    expect(lookup('next', '', '^15.0.0')).toEqual(['15.1.0']);
  });
});

describe('uv.lock and poetry.lock', () => {
  it('lists versions by normalised name', () => {
    const lookup = parsePackageListLock(`version = 1
[[package]]
name = "Django"
version = "4.2.30"

[[package]]
name = "django-filter"
version = "23.5"
`);
    expect(lookup('django', '', null)).toEqual(['4.2.30']);
    expect(lookup('Django_Filter', '', null)).toEqual(['23.5']);
    expect(lookup('flask', '', null)).toEqual([]);
  });
});

describe('requirements and PEP 508', () => {
  it('parses names, specs, extras and markers, and skips options and URLs', () => {
    const deps = parseRequirements(
      `# comment
-r base.txt
--index-url https://example.org/simple
Django==3.2.25  # pinned
djangorestframework>=3.14,<4
celery[redis]==5.3.6 ; python_version >= "3.8"
-e git+https://github.com/x/y.git#egg=y
https://example.org/pkg.tar.gz
pkg @ https://example.org/pkg.whl
`,
      'prod',
    );
    expect(deps).toEqual([
      { name: 'Django', kind: 'prod', spec: '==3.2.25' },
      { name: 'djangorestframework', kind: 'prod', spec: '>=3.14,<4' },
      { name: 'celery', kind: 'prod', spec: '==5.3.6' },
    ]);
  });

  it('pins only exact versions', () => {
    expect(pinnedVersion('==3.2.25')).toBe('3.2.25');
    expect(pinnedVersion('===1.0')).toBe('1.0');
    expect(pinnedVersion('>=3.2')).toBeNull();
    expect(pinnedVersion('==3.2.*')).toBeNull();
    expect(pinnedVersion(null)).toBeNull();
    expect(parseRequirement('Django (>=3.2)')).toEqual({ name: 'Django', spec: '>=3.2' });
    expect(normalizePyName('Django_Rest.Framework')).toBe('django-rest-framework');
  });

  it('pyproject: PEP 621, optional, dependency groups and Poetry', () => {
    const p = parsePyproject(`[project]
name = "a"
dependencies = ["Django>=4.2,<5"]
[project.optional-dependencies]
pg = ["psycopg>=3"]
[dependency-groups]
dev = ["pytest>=8"]
[tool.poetry.dependencies]
python = "^3.10"
celery = { version = "^5.3", extras = ["redis"] }
[tool.poetry.group.test.dependencies]
factory-boy = "^3.3"
`);
    expect(p.deps).toEqual([
      { name: 'Django', kind: 'prod', spec: '>=4.2,<5' },
      { name: 'psycopg', kind: 'optional', spec: '>=3' },
      { name: 'pytest', kind: 'dev', spec: '>=8' },
      { name: 'celery', kind: 'prod', spec: '^5.3' },
      { name: 'factory-boy', kind: 'dev', spec: '^3.3' },
    ]);
  });
});

describe('tsconfig JSONC', () => {
  it('accepts comments and trailing commas but keeps // inside strings', () => {
    expect(parseJsonc('{\n // c\n "a": "http://x", /* b */ "c": [1, 2,],\n}')).toEqual({ a: 'http://x', c: [1, 2] });
  });
});
